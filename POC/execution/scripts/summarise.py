"""Collect per-split eval summaries into outputs/b0_results.{json,md}.

Aggregates only (no imagery, no per-pair captions), so the outputs can be
committed. Run after evaluate.py has written eval_summary_<split>.json files.
"""
import json
from pathlib import Path

import sys

sys.path.insert(0, str(Path(__file__).parent))
from common import DATA, EXEC_ROOT, RUNS, dataset_meta  # noqa: E402

ORDER = ["C02", "C02-r20", "C04", "C07", "CTRL_evidence_template", "CTRL_constant_nochange"]
NAMES = {"C02": "RSCaMa (specialist)", "C02-r20": "RSCaMa retrained on 20% (ours)", "C04": "Qwen3-VL-4B", "C07": "SmolVLM2-2.2B",
         "CTRL_evidence_template": "Evidence template (pixel difference)",
         "CTRL_constant_nochange": "Constant \"there is no difference\""}
SPLITS = ["screening", "development"]


def pct(x):
    return "n/a" if x is None else f"{100 * x:.1f}%"


def main():
    results = []
    for d in sorted(RUNS.glob("B0_*")):
        for split in SPLITS:
            f = d / f"eval_summary_{split}.json"
            if f.exists():
                s = json.load(open(f))
                s["split"] = split
                s["model_name"] = NAMES.get(s["role_model_id"], s["role_model_id"])
                results.append(s)
    results.sort(key=lambda s: (SPLITS.index(s["split"]), ORDER.index(s["role_model_id"]) if s["role_model_id"] in ORDER else 99))
    out = EXEC_ROOT / "outputs"
    out.mkdir(exist_ok=True)
    suffix = "" if RUNS.name == "runs" else f"_ood_{DATA.name}"  # B_DATA set: out-of-domain set
    json.dump(results, open(out / f"b0_results{suffix}.json", "w"), indent=1)

    lines = [f"# B0 results{' on ' + dataset_meta()['dataset'] if suffix else ''} (auto-generated by scripts/summarise.py)", "",
             "Automatic reference check (oracle masks + 5 reference captions), not the human audit. "
             "Latency is Apple M4 (MPS), batch 1.", ""]
    for split in SPLITS:
        rows = [s for s in results if s["split"] == split]
        if not rows:
            continue
        lines += [f"## {split} ({rows[0]['pairs']} pairs)", "",
                  "| System | Claim precision (95% CI) | Fact recall (95% CI) | False alarms on unchanged | Missed changes | Claims/pair | BLEU-4 | CIDEr-D | Median s/pair |",
                  "|---|---|---|---|---|---|---|---|---|"]
        for s in rows:
            ci_p = s.get("supported_claim_precision_strict_ci95") or [None, None]
            ci_r = s.get("reference_fact_recall_ci95") or [None, None]
            tm = s.get("text_metrics") or {}
            lines.append(
                f"| {s['model_name']} | {pct(s['supported_claim_precision_strict'])} ({pct(ci_p[0])}–{pct(ci_p[1])}) "
                f"| {pct(s['reference_fact_recall'])} ({pct(ci_r[0])}–{pct(ci_r[1])}) "
                f"| {pct(s['no_change_false_alarm_rate'])} of {s['unchanged_pairs_clean']} "
                f"| {pct(s['missed_change_rate'])} of {s['changed_pairs_clean']} "
                f"| {s['claims_per_pair']} | {tm.get('BLEU-4', 'n/a')} | {tm.get('CIDEr-D', 'n/a')} "
                f"| {s.get('warm_latency_median_s') if s.get('warm_latency_median_s') is not None else 'n/a'} |")
        lines.append("")
    (out / f"b0_results{suffix}.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
